const BY_LOWER = new Map(Object.entries(MEDIA_IDS).map(([k, v]) => [k.toLowerCase(), v]));

/** Two photo URLs (start and finish position) for an exercise, or null when we have no match. */
export function mediaFor(name) {
  const id = BY_LOWER.get(String(name || '').trim().toLowerCase());
  return id ? { id, images: [`${MEDIA_BASE}/${id}/0.jpg`, `${MEDIA_BASE}/${id}/1.jpg`] } : null;
}
